import { Signal } from '@angular/core';
import { toSignal } from '@angular/core/rxjs-interop';
import { TranslateService } from '@ngx-translate/core';
import { map } from 'rxjs/operators';

// Read it in a computed() that calls TranslateService.instant, so the result follows a runtime language switch.
export function currentLangSignal(translate: TranslateService): Signal<string> {
  return toSignal(translate.onLangChange.pipe(map(event => event.lang)), {initialValue: translate.currentLang});
}
